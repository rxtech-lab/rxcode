    func lastAssistantResponseText(in messages: [ChatMessage]) -> String {
        // Walk back to the most recent assistant message that actually has text.
        // A turn often ends on a tool-call-only (or thinking-only) assistant
        // message whose `content` — the joined text blocks — is empty. Taking
        // `messages.last` blindly would return "" and collapse the notification
        // body to the "Response complete" fallback, hiding the real summary.
        for message in messages.reversed() where message.role == .assistant && !message.isError {
            let text = message.content.trimmingCharacters(in: .whitespacesAndNewlines)
            if !text.isEmpty { return text }
        }
        return ""
    }

    func lastUserMessageText(in messages: [ChatMessage]) -> String {
        guard let message = messages.last(where: { $0.role == .user && !$0.isError }) else {
            return ""
        }
        return ChatSession.stripAttachmentMarkers(from: message.content)
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    func userMessageTexts(in messages: [ChatMessage]) -> [String] {
        messages
            .filter { $0.role == .user && !$0.isError }
            .map { ChatSession.stripAttachmentMarkers(from: $0.content).trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
    }

    func responseNotificationFallback(from responseText: String) -> String {
        let text = responseText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return "" }
        let sentence = text.components(separatedBy: CharacterSet(charactersIn: ".!?\n")).first ?? text
        return sentence.trimmingCharacters(in: .whitespaces)
    }

    func selectedSummarizationModel(for provider: AgentProvider) -> String? {
        if selectedAgentProvider == provider {
            return selectedModel
        }
        return availableAgentModelSections()
            .first(where: { $0.provider == provider })?
            .models
            .first?
            .id
    }

    /// One-shot completion used by the Send Message hook's condition gate. Honors
    /// a per-hook provider/model `overrideSelection`; otherwise routes through the
    /// configured `summarizationProvider` (defaulting to the thread's model for the
    /// `.selectedClient` case). Returns nil when no engine could run; callers
    /// treat that as "do not fire".
    func runHookConditionCompletion(
        prompt: String,
        overrideSelection: (provider: AgentProvider, model: String)?,
        fallbackSessionId: String
    ) async -> String? {
        if let sel = overrideSelection {
            switch sel.provider {
            case .claudeCode:
                return await claude.generatePlainSummary(prompt: prompt, model: sel.model, limit: 200)
            case .codex:
                return await codex.generateCodexPlainSummary(prompt: prompt, model: sel.model)
            case .acp, .localAgent, .flowcy:
                break // ACP has no one-shot; fall through to the summarization model.
            }
        }

        switch summarizationProvider {
        case .selectedClient:
            let summary = allSessionSummaries.first { $0.id == fallbackSessionId }
            let provider = summary?.agentProvider ?? selectedAgentProvider
            let model = summary?.model ?? selectedSummarizationModel(for: provider)
            switch provider {
            case .claudeCode:
                return await claude.generatePlainSummary(prompt: prompt, model: model ?? "haiku", limit: 200)
            case .codex:
                return await codex.generateCodexPlainSummary(prompt: prompt, model: model)
            case .acp, .localAgent, .flowcy:
                // ACP can't run a one-shot; fall back to a cheap Claude classifier.
                return await claude.generatePlainSummary(prompt: prompt, model: "haiku", limit: 200)
            }
        case .openAI:
            guard !openAISummarizationModel.isEmpty else {
                return await claude.generatePlainSummary(prompt: prompt, model: "haiku", limit: 200)
            }
            return await openAISummarization.generatePlainCompletion(
                prompt: prompt,
                endpoint: openAISummarizationEndpoint,
                apiKey: openAISummarizationAPIKey,
                model: openAISummarizationModel,
                maxTokens: 16
            )
        case .appleFoundationModel:
            return await foundationModelSummarization.generatePlainCompletion(
                instructions: "You answer strictly with YES or NO.",
                prompt: prompt
            )
        }
    }

    func togglePinSession(_ session: ChatSession) async {
        guard let si = allSessionSummaries.firstIndex(where: { $0.id == session.id }) else { return }
        allSessionSummaries[si].isPinned.toggle()
        let newIsPinned = allSessionSummaries[si].isPinned
        threadStore.upsert(allSessionSummaries[si])
        await updateSessionMetadata(session) { $0.isPinned = newIsPinned }
        scheduleMobileSnapshotBroadcast()
    }

