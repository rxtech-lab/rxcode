    func scheduleThreadSummaryUpdate(
        sessionId: String,
        projectId: UUID,
        cwd: String,
        messages: [ChatMessage]
    ) {
        let userMessage = lastUserMessageText(in: messages)
        let finalResponse = lastAssistantResponseText(in: messages)
        guard !userMessage.isEmpty, !finalResponse.isEmpty else { return }

        let summary = allSessionSummaries.first(where: { $0.id == sessionId })
            ?? summaryFor(sessionId: sessionId, projectId: projectId)

        Task { [weak self] in
            guard let self else { return }
            await self.updateStoredThreadSummary(
                sessionId: sessionId,
                projectId: projectId,
                cwd: cwd,
                userMessage: userMessage,
                finalResponse: finalResponse,
                summary: summary
            )
        }
    }

    func updateStoredThreadSummary(
        sessionId: String,
        projectId: UUID,
        cwd: String,
        userMessage: String,
        finalResponse: String,
        summary: ChatSession.Summary
    ) async {
        // `[Code Review]` threads are excluded from briefings (and from the
        // branch briefing aggregation below) — they review the work, they aren't
        // part of the branch's story.
        guard summary.projectId != Project.globalChatID,
              summary.threadLabel != Self.manualCodeReviewLabel else { return }

        let branchPath = summary.worktreePath ?? cwd
        let observedBranch = if let worktreeBranch = summary.worktreeBranch {
            worktreeBranch
        } else {
            await GitHelper.currentBranch(at: branchPath)
        }
        let storedSummary = threadStore.threadSummaryItem(sessionId: sessionId)
        let title = summary.title.isEmpty ? ChatSession.defaultTitle : summary.title

        // Keep the branch association even when summarization is unavailable.
        if let observedBranch, observedBranch != storedSummary?.branch {
            threadStore.upsertThreadSummaryTitle(
                sessionId: sessionId,
                projectId: projectId,
                branch: observedBranch,
                title: title
            )
            threadSummaryRevision &+= 1
        }

        guard let threadSummary = await generateThreadSummary(
            previousSummary: storedSummary?.summary,
            userMessage: userMessage,
            finalResponse: finalResponse,
            summary: summary
        ) else { return }

        let branch = observedBranch ?? storedSummary?.branch ?? "unknown"

        threadStore.upsertThreadSummary(
            sessionId: sessionId,
            projectId: projectId,
            branch: branch,
            title: title,
            summary: threadSummary,
            createdAt: summary.createdAt
        )
        threadSummaryRevision &+= 1

        // Briefings are per day: a chat belongs to the day it was created, and
        // that day's briefing is rebuilt from the chats started on it.
        let calendar = Calendar.current
        let chatDay = threadStore.threadSummaryItem(sessionId: sessionId)?.createdAt ?? summary.createdAt
        let dayThreadSummaries = threadStore
            .threadSummaryItems(projectId: projectId, branch: branch)
            .filter { calendar.isDate($0.createdAt, inSameDayAs: chatDay) }
            .map { (title: $0.title, summary: $0.summary) }
        let activity = (try? await codingPlanActivities(projectID: projectId)) ?? []
        let dayPlans = activity.filter {
            ($0.branch ?? "unknown") == branch && calendar.isDate($0.updatedAt, inSameDayAs: chatDay)
        }
        guard !dayThreadSummaries.isEmpty || !dayPlans.isEmpty else { return }
        let prompt = OpenAISummarizationService.branchBriefingPrompt(threadSummaries: dayThreadSummaries, plans: dayPlans)
        guard let briefing = await generateBranchBriefing(
            prompt: prompt,
            summary: summary
        ) else { return }

        threadStore.upsertBranchBriefing(projectId: projectId, branch: branch, day: chatDay, briefing: briefing)
        branchBriefingRevision &+= 1
    }

